/**
 * Ячейка CSV для разовых выгрузок (`export-leads.mjs`, `export-reviews.mjs`).
 *
 * Экранирование по RFC 4180: кавычки удваиваются, поле берётся в кавычки.
 * Значение, которое табличный редактор исполнил бы как формулу, получает
 * апостроф — то же правило, что у выгрузок кабинета (`src/lib/cabinet/
 * csv.ts`, Р-183, Р-235). Имя, отзыв и сообщение приходят с открытой формы
 * сайта, и `=HYPERLINK(…)` в них исполнился бы на машине того, кто открыл
 * выгрузку (решение Р-425).
 */
export function cell(value) {
  const s = value == null ? '' : String(value);
  const guarded = /^[=+\-@\t\r]/.test(s) ? `'${s}` : s;
  return '"' + guarded.replace(/"/g, '""') + '"';
}
