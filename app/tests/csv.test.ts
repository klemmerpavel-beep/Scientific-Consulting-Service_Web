/**
 * Выгрузка журнала в таблицу (решение Р-183).
 *
 * Модуль журналов не имел ни одной проверки, хотя выгрузка уходит на
 * машину проверяющего и открывается табличным редактором. Опасны две
 * вещи: формула, подставленная в поле и выполненная при открытии, и
 * кавычка, разрывающая строку. Обе закрыты экранированием, и здесь оно
 * и проверяется — без базы, потому что это чистая функция.
 */

import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import { toCsv } from '../src/lib/cabinet/csv.ts';

describe('выгрузка журнала', () => {
  it('ставит метку порядка байтов', () => {
    // Без неё табличный редактор читает кириллицу кодировкой системы.
    assert.ok(toCsv([['Дата']]).startsWith('﻿'));
  });

  it('разделяет поля точкой с запятой, строки — CRLF', () => {
    assert.equal(toCsv([['a', 'b'], ['c', 'd']]), '﻿"a";"b"\r\n"c";"d"\r\n');
  });

  it('кавычка внутри значения удваивается', () => {
    assert.equal(toCsv([['он сказал "да"']]), '﻿"он сказал ""да"""\r\n');
  });

  it('значение, начинающееся со знака формулы, обезврежено', () => {
    // Иначе редактор выполнит его при открытии файла.
    for (const start of ['=', '+', '-', '@', '\t', '\r']) {
      const out = toCsv([[`${start}HYPERLINK("http://x")`]]);
      assert.ok(
        out.includes(`"'${start}HYPERLINK`),
        `значение с «${JSON.stringify(start)}» не обезврежено: ${out}`,
      );
    }
  });

  it('точка с запятой и перевод строки внутри значения не рвут таблицу', () => {
    const out = toCsv([['первое; второе\nтретье']]);
    // Значение целиком в кавычках, и разделителей вне кавычек нет.
    assert.equal(out, '﻿"первое; второе\nтретье"\r\n');
  });

  it('пустая выгрузка остаётся пустой строкой с меткой', () => {
    assert.equal(toCsv([]), '﻿\r\n');
  });
});
