/**
 * Короткие предлоги и союзы в текстах разделов (методика §8, DESIGN-SYSTEM
 * §3.4, Р-86, Р-1005): после предлога или союза в одну-две буквы — неразрывный
 * пробел, чтобы слово не оставалось в конце строки.
 *
 * `bind` переводит строку в набор Р-1005 — им тесты, сверяющие тексты
 * дословно, задают ожидаемое; `unbind` снимает этот набор, когда тест сверяет
 * слова, а не набор.
 */

/** Предлоги и союзы в одну-две буквы. */
export const SHORT_WORDS = ['в', 'во', 'к', 'ко', 'с', 'со', 'о', 'об', 'у', 'на', 'по', 'за', 'до', 'из', 'от', 'и', 'а', 'но'] as const;

const ALT = SHORT_WORDS.join('|');
/** Обычный пробел после короткого слова, перед непробельным знаком; слово — отдельное (не часть слова, номера, адреса). */
export const LOOSE = new RegExp(`(?<![\\p{L}\\p{N}_\\-.\\u00a0/@])(${ALT}) (?=\\S)`, 'giu');

export const bind = (text: string): string => text.replace(LOOSE, '$1 ');
export const unbind = (text: string): string => text.replace(new RegExp(`(?<![\\p{L}\\p{N}_])(${ALT})\\u00a0`, 'giu'), '$1 ');
