/**
 * Документ Word для проверок разбора (решение Р-556): настоящий OOXML с
 * абзацами и таблицами, без сторонних библиотек — архив собирает `zip`
 * проверок книги заказов.
 *
 * Абзац можно задать фрагментами: Word дробит текст на `w:r` по правке и
 * оформлению, и разбор обязан склеивать их.
 */

import { zip } from './make-workbook.ts';

export type DocxBlock =
  | string
  | { readonly runs: readonly string[] }
  /** Абзац с разрывом строки (Shift + Enter) между частями. */
  | { readonly lines: readonly string[] }
  | { readonly table: readonly (readonly string[])[] };

const escape = (text: string) => text.replace(/&/gu, '&amp;').replace(/</gu, '&lt;').replace(/>/gu, '&gt;');

const run = (text: string) => `<w:r><w:rPr><w:sz w:val="28"/></w:rPr><w:t xml:space="preserve">${escape(text)}</w:t></w:r>`;

function paragraph(parts: readonly string[]): string {
  return `<w:p><w:pPr><w:jc w:val="both"/></w:pPr>${parts.map(run).join('')}</w:p>`;
}

function cell(text: string): string {
  // Перевод строки в ячейке — новый абзац, как в Word.
  return `<w:tc><w:tcPr><w:tcW w:w="4500" w:type="dxa"/></w:tcPr>${text.split('\n').map((line) => paragraph([line])).join('')}</w:tc>`;
}

export function documentXml(blocks: readonly DocxBlock[]): string {
  const body = blocks
    .map((block) => {
      if (typeof block === 'string') return paragraph([block]);
      if ('runs' in block) return paragraph(block.runs);
      if ('lines' in block) return `<w:p>${block.lines.map((text, index) => (index === 0 ? run(text) : `<w:r><w:br/><w:t xml:space="preserve">${escape(text)}</w:t></w:r>`)).join('')}</w:p>`;
      return `<w:tbl><w:tblPr/>${block.table.map((row) => `<w:tr>${row.map(cell).join('')}</w:tr>`).join('')}</w:tbl>`;
    })
    .join('<w:p/>');
  return (
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' +
    '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>' +
    body +
    '<w:sectPr/></w:body></w:document>'
  );
}

export function makeDocx(blocks: readonly DocxBlock[], author: string | null = null): Buffer {
  const files: { name: string; content: string }[] = [
    {
      name: '[Content_Types].xml',
      content:
        '<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">' +
        '<Default Extension="xml" ContentType="application/xml"/>' +
        '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>',
    },
    { name: 'word/document.xml', content: documentXml(blocks) },
  ];
  if (author !== null) {
    files.push({
      name: 'docProps/core.xml',
      content:
        '<?xml version="1.0" encoding="UTF-8"?><cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" xmlns:dc="http://purl.org/dc/elements/1.1/">' +
        `<dc:creator>${escape(author)}</dc:creator><cp:lastModifiedBy>${escape(author)}</cp:lastModifiedBy></cp:coreProperties>`,
    });
  }
  return zip(files);
}

