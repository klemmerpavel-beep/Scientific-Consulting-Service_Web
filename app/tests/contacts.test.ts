/**
 * Обнаружение контактных данных в переписке. Проверяется на формулировках,
 * которые встречаются в живом обсуждении: важно и то, что детектор ловит,
 * и то, что он не срабатывает на номерах пунктов, ГОСТах и суммах.
 */

import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import { findContacts, hasContacts } from '../src/lib/cabinet/contacts.ts';

describe('детектор ловит передачу контактов', () => {
  const cases: [string, string][] = [
    ['адрес почты', 'Пришлите на ivan.petrov@example.ru, так быстрее'],
    ['телефон с кодом страны', 'Мой номер +7 999 000-00-00, наберите вечером'],
    ['телефон без кода страны', 'Звоните 8 (495) 456-43-23'],
    ['телефон слитно', 'Вот номер: 79990000000'],
    ['имя в мессенджере', 'Пишите мне @ivan_petrov, там отвечаю быстрее'],
    ['ссылка на мессенджер', 'Продолжим в https://t.me/ivan_petrov'],
  ];
  for (const [name, text] of cases) {
    it(name, () => {
      assert.equal(hasContacts(text), true, `не поймано: ${text}`);
    });
  }

  it('вид найденного различается', () => {
    assert.deepEqual(
      findContacts('почта a@b.ru и номер +7 999 000-00-00').map((h) => h.kind).sort(),
      ['email', 'phone'],
    );
  });
});

describe('детектор не срабатывает на рабочем тексте', () => {
  const cases: [string, string][] = [
    ['номер пункта', 'В п. 2.3 нужна фактическая наработка на отказ'],
    ['ГОСТ', 'Оформление по ГОСТ Р 58048-2017, раздел 5.2'],
    ['сумма договора', 'Второй транш по договору — 240 000 рублей'],
    ['код проекта', 'Работаем по проекту PD-2026-014'],
    ['дата', 'Защита назначена на 02.09.2027'],
    ['диапазон страниц', 'Посмотрите страницы 145-160 и 201-233'],
    ['адрес электронной почты компании в подписи', 'Вопросы — менеджеру проекта'],
  ];
  for (const [name, text] of cases) {
    it(name, () => {
      assert.equal(hasContacts(text), false, `ложное срабатывание: ${text}`);
    });
  }
});
