// Проект собирается в двух видах.
//
// Рабочий сайт — самодостаточная сборка для контейнера на российском
// сервере: она запускается как `node .next/standalone/server.js` и умеет
// принимать заявки.
//
// Витрина — статические файлы для показа проекта: страницы и переходы
// работают, сервера за ними нет, приём заявок отключён (см. submit-lead).
// Лежит в подпапке домена, поэтому ссылки и адреса ресурсов получают
// общий префикс из PREVIEW_BASE_PATH.
const preview = process.env.NEXT_PUBLIC_PREVIEW === '1';
const basePath = preview ? (process.env.PREVIEW_BASE_PATH ?? '') : '';

/**
 * Политика содержимого.
 *
 * Запрещено главное: чужие сценарии, кадры и объекты, встраивание сайта в
 * чужую страницу и отправка форм на чужой адрес. Сетевые запросы — только
 * к своему источнику; письма и Telegram уходят с сервера, браузеру наружу
 * ходить незачем.
 *
 * 'unsafe-inline' оставлен сознательно и в обоих местах по разным причинам.
 * Стили: страницы перенесены из макетов и держат оформление в атрибутах
 * style — вынести их в файл значит переписать перенос целиком. Сценарии:
 * Next вставляет в разметку встроенные вставки для оживления страницы;
 * убрать их можно только одноразовым кодом из middleware, а он переводит
 * все страницы в динамическую отрисовку и лишает сайт предсобранной
 * статики. Ни в одну страницу не попадает текст, полученный от посетителя,
 * поэтому вставить свой сценарий через содержимое некуда.
 */
/**
 * Счётчик посещаемости требует четырёх послаблений разом: чужой сценарий,
 * его пиксель, его запросы и его кадр синхронизации. Послабления выдаются
 * только когда счётчик действительно включён — по заданному номеру. Пока
 * номера нет, политика остаётся закрытой полностью, и «подготовленный к
 * аналитике» сайт ничем не отличается от сайта без аналитики.
 */
const metrika = process.env.NEXT_PUBLIC_METRIKA_ID ? ' https://mc.yandex.ru' : '';

const CSP = [
  "default-src 'self'",
  "base-uri 'none'",
  "object-src 'none'",
  metrika ? `frame-src${metrika}` : "frame-src 'none'",
  "frame-ancestors 'none'",
  "form-action 'self'",
  `img-src 'self' data:${metrika}`,
  "font-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  `script-src 'self' 'unsafe-inline'${metrika}`,
  `connect-src 'self'${metrika}`,
  'upgrade-insecure-requests',
].join('; ');

/** @type {import('next').NextConfig} */
const nextConfig = {
  ...(preview
    ? {
        output: 'export',
        basePath,
        assetPrefix: basePath || undefined,
        images: { unoptimized: true },
        trailingSlash: true,
      }
    : {
        output: 'standalone',
        // Оптимизатор изображений не используется: страницы перенесены из
        // макетов и ставят снимки обычным тегом img. Включённым он всё
        // равно открывает наружу /_next/image и пропускает файлы через
        // sharp — лишняя поверхность без единого потребителя. Выключаем.
        images: { unoptimized: true },
        // Файлы в кабинет идут серверными действиями, а у них предел тела
        // по умолчанию 1 МБ: глава диссертации в PDF отсекалась ответом
        // 413 раньше, чем кабинет проверял размер. Предел — обращение из
        // пяти файлов по 25 МБ с запасом на поля формы; nginx держит тот же
        // предел для /cabinet (решение Р-231).
        experimental: { serverActions: { bodySizeLimit: '130mb' } },
      }),

  poweredByHeader: false,
  reactStrictMode: true,

  // Заголовки безопасности выставляет сервер. В статической витрине сервера
  // нет — там их задаёт площадка, и объявлять их здесь бессмысленно.
  ...(preview
    ? {}
    : {
        /**
         * Прототип кабинета лежит статикой в `public/cabinet-preview` и
         * открывается по адресу `/cabinet-preview/` (решение Р-174).
         *
         * Next отдаёт файлы из `public` только по точному пути и каталожный
         * адрес в `index.html` не разворачивает. Раньше это чинилось
         * подменой адреса (`rewrites`), и она давала страницу без единого
         * стиля: адрес в строке оставался `/cabinet-preview` — без
         * завершающей косой черты, — а относительные ссылки копии
         * (`prototype.css`, переходы по ролям) отсчитываются от него, то
         * есть уходили в корень домена. Теперь адрес не подменяется, а
         * переводится: человек попадает на `/cabinet-preview/index.html`,
         * и всё относительное считается от каталога копии (решение Р-179).
         *
         * Перевод — точный, без образца с хвостом: правила перевода
         * разбираются до файловой системы, и образец `:path*` увёл бы в
         * никуда и таблицу стилей, и каждый снимок.
         */
        async redirects() {
          return [
            {
              source: '/cabinet-preview',
              destination: '/cabinet-preview/index.html',
              permanent: false,
            },
          ];
        },

        async headers() {
          return [
            {
              source: '/:path*',
              headers: [
                { key: 'X-Content-Type-Options', value: 'nosniff' },
                { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
                { key: 'X-Frame-Options', value: 'DENY' },
                {
                  key: 'Permissions-Policy',
                  value: 'camera=(), microphone=(), geolocation=(), interest-cohort=()',
                },
                { key: 'Content-Security-Policy', value: CSP },
              ],
            },
          ];
        },
      }),
};

export default nextConfig;
