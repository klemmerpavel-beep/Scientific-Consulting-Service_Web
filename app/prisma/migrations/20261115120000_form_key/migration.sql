-- Одноразовый ключ формы (решение Р-934).
--
-- Форма, отправленная повторно — из дубля вкладки, кнопкой «назад» или
-- повтором запроса при обрыве связи, — записывала поступление, начисление,
-- заказ или заявку второй раз (аудит 15.11.2026, находка Ф-9). Форма несёт
-- случайный ключ; действие занимает его перед записью, и вторая отправка
-- с тем же ключом получает отказ. Ключ хранится двое суток.
--
-- Таблица новая, существующие не меняются: прежняя версия приложения её не
-- знает и продолжает работать (DEPLOY.md, § 5г). Откат — удалить таблицу:
-- DROP TABLE "FormKey";
CREATE TABLE "FormKey" (
    "key" TEXT NOT NULL,
    "userId" TEXT NOT NULL,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "FormKey_pkey" PRIMARY KEY ("key")
);

CREATE INDEX "FormKey_createdAt_idx" ON "FormKey"("createdAt");
