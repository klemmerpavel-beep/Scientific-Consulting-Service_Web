-- Р-257: день начала у работ, заведённых в кабинете. Прежде его ставил
-- только перенос книги заказов; работы из одобренных заявок оставались без
-- него и выпадали из счёта «Принято за квартал», заказов по месяцам и итогов
-- по годам. День берётся по Москве из момента создания работы.
UPDATE "Project"
SET "startedOn" = date_trunc('day', ("createdAt" AT TIME ZONE 'UTC') AT TIME ZONE 'Europe/Moscow')
WHERE "startedOn" IS NULL AND "source" = 'WEB';
