-- П-12, Р-768: согласия куратора отмечает сам куратор.
--
-- Согласие на камеру на созвоне знакомства — днём отметки, а не признаком
-- «да/нет»: руководитель видит отметку и дату. У согласия на витрину
-- кураторов — свёртка (SHA-256) текста, на который оно дано: текст вносит
-- руководитель в настройках практики, и при его смене прежнее согласие
-- считается данным на прежний текст.
--
-- Отметки, поставленные руководителем со слов куратора (Р-764), снимаются:
-- куратор их не видел и текста согласия не читал, а у витрины текста не
-- было вовсе (ст. 10.1 152-ФЗ). Куратор отмечает согласия заново сам.
ALTER TABLE "ExpertProfile"
  ADD COLUMN "cameraConsentAt" TIMESTAMP(3),
  ADD COLUMN "showcaseConsentHash" TEXT,
  DROP COLUMN "cameraConsent";

UPDATE "ExpertProfile" SET "showcaseConsentAt" = NULL WHERE "showcaseConsentAt" IS NOT NULL;
