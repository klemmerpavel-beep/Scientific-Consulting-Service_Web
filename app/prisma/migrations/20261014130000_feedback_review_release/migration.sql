done AS (
  UPDATE "Feedback" AS f
     SET status = 'FIXED',
         note = v.note,
         "resolvedAt" = COALESCE(v.resolved, now() AT TIME ZONE 'UTC'),
         "updatedAt" = now() AT TIME ZONE 'UTC'
    FROM v
   WHERE f.id = v.id
     AND f.status = 'NEW'
  RETURNING f.id, f.severity::text AS severity
)
INSERT INTO "AuditEvent" (id, "occurredAt", action, "objectType", "objectId", payload)
