       done.id,
       jsonb_build_object(
         'status', jsonb_build_object('from', 'NEW', 'to', 'FIXED'),
         'severity', jsonb_build_object('from', done.severity, 'to', done.severity),
         'note', true,
         'via', 'release'
       )
  FROM done;
