-- Ветка переписки «куратор — менеджер» по работе (решение Р-935).
--
-- Куратору нечем было задать вопрос менеджеру в кабинете: внутренняя ветка
-- работы — менеджер и руководитель (Р-336), в переписку с клиентом куратор
-- не входит (Р-150). Оставалось письмо из почтовой программы — при правиле
-- «общение только в кабинете» (аудит 15.11.2026, находка Н-6). Новая ветка
-- — отдельное значение: прежние сообщения внутренней ветки куратору не
-- открываются.
--
-- Добавляется только значение перечисления, строки не меняются: прежняя
-- версия приложения его не знает и продолжает работать (DEPLOY.md, § 5г).
-- Откат — убрать сообщения ветки; само значение перечисления в PostgreSQL
-- не удаляется и без сообщений ничему не мешает.
ALTER TYPE "MessageThread" ADD VALUE 'WORK_CURATOR';
