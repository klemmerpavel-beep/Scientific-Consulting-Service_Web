'use client';

/**
 * Фокус на исходе действия (аудит 15.11.2026, находка Д-2; решение Р-919).
 *
 * После серверного действия экран открывается заново, и фокус падал на
 * документ: человек с клавиатурой начинал обход с шапки, а читалка не
 * произносила ни подтверждения, ни причины отказа — область `alert` или
 * `status` объявляется, только когда появляется на уже открытой странице.
 * При отказе окно к тому же оставалось вверху, далеко от формы.
 *
 * Блок исхода получает фокус сам: читалка читает его текст, окно
 * подводится к нему, а следующее нажатие Tab ведёт к форме под ним. В
 * порядок обхода блок не входит (`tabindex="-1"`).
 */

import { useEffect, useRef } from 'react';

export default function OutcomeFocus({ mark }: { mark: string }) {
  const anchor = useRef<HTMLSpanElement>(null);
  useEffect(() => {
    anchor.current?.closest<HTMLElement>('.cab-outcome')?.focus();
    // `mark` меняется с каждым новым исходом: без него повторный отказ в
    // той же форме фокуса бы не получил — блок на странице тот же.
  }, [mark]);
  return <span ref={anchor} hidden />;
}
