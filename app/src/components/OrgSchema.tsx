import { siteUrl } from '../lib/site-url';

/**
 * Описание организации для поисковых систем (schema.org, JSON-LD).
 *
 * Нужно ровно для одного: чтобы в выдаче и в карточке организации стояли
 * наши реквизиты, а не то, что поисковик соберёт по крупицам со сторонних
 * площадок. Все значения совпадают с подвалом сайта и с реквизитами в
 * правовых документах — расхождение здесь читается поисковиком как признак
 * недостоверности, а проверяющим как расхождение сведений.
 *
 * Разметка не описывает услуги и цены: цены на сайте не публикуются
 * (решение Р-03), а перечислять услуги второй раз в машинном виде значит
 * заводить второй источник правды рядом со страницами.
 */
const ORG = {
  '@context': 'https://schema.org',
  '@type': 'ProfessionalService',
  name: 'ProDisser',
  legalName: 'Общество с ограниченной ответственностью «РУСДРОН»',
  description:
    'Научно-консультационное сопровождение диссертаций, публикаций и '
    + 'исследовательских работ: методология, экспертиза, подготовка к защите.',
  email: 'info.prodisser@gmail.com',
  telephone: '+7 495 456 43 23',
  taxID: '9723254250',
  vatID: '9723254250',
  address: {
    '@type': 'PostalAddress',
    addressCountry: 'RU',
    addressLocality: 'Москва',
    postalCode: '109451',
    streetAddress: 'б-р Перервинский, д. 27, к. 1, помещ. 10н',
  },
  areaServed: 'RU',
  knowsLanguage: 'ru',
  sameAs: ['https://t.me/prodisser', 'https://vk.ru/cmnrut'],
};

export default function OrgSchema() {
  const url = siteUrl();
  // Без известного адреса сайта разметка бесполезна: поисковику не к чему
  // привязать организацию. В витрине её нет и при заданном адресе — это
  // демонстрационный стенд, и заявлять на нём организацию с её реквизитами
  // значит плодить второй «официальный» адрес компании.
  if (!url || process.env.NEXT_PUBLIC_PREVIEW === '1') return null;

  const data = { ...ORG, url, logo: `${url}/icon.svg`, image: `${url}/og-cover.png` };

  return (
    <script
      type="application/ld+json"
      // Данные наши собственные и статические: подставлять сюда нечего,
      // экранировать нечего.
      dangerouslySetInnerHTML={{ __html: JSON.stringify(data) }}
    />
  );
}
