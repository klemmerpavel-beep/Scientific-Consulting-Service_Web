/**
 * Соответствие «слот в макете → снимок» и правила кадрирования.
 *
 * Пять снимков пришли внутри автономной сборки посадочной страницы, где были
 * упакованы как WebP с прозрачным фоном. Соответствие слотов взято оттуда же.
 *
 * ——— Почему здесь измерения, а не подобранные множители ———
 *
 * Сначала фигуры выравнивались множителем высоты: «фигура во столько-то раз
 * выше слота». В трёх соседних карточках направлений это дало разъезд —
 * головы обрезало сверху, а студентка уехала вправо. Причина в самих файлах:
 * люди стоят в кадре по-разному. У студентки голова смещена на 12,5 % вправо
 * от центра кадра, потому что она держит ноутбук слева. У аспиранта над
 * головой всего три пикселя запаса. Геометрия слота про это ничего не знает.
 *
 * Поэтому каждый снимок измерен по своему содержимому: где начинается
 * фигура, какой ширины голова и где её центр. Кадрирование считается из
 * этих чисел, а не подбирается на глаз:
 *
 *   · масштаб берётся так, чтобы голова вышла заданной ширины — тогда лица
 *     в соседних карточках одного размера, даже если снимки разной крупности;
 *   · снимок сдвигается так, чтобы центр головы попал в центр слота —
 *     тогда человек стоит по центру, а не «где получилось»;
 *   · сверху остаётся заданный воздух — тогда причёску не срезает.
 *
 * Измерения получены по альфа-каналу файлов: границы непрозрачной области
 * и её ширина в верхних 18 % фигуры (это голова с плечами). Пересчитывать
 * при замене файла — командой из docs/PHOTOS.md.
 *
 * Условие публикации каждого портрета — письменное согласие изображённого
 * лица. Решение Р-08 в docs/DECISIONS.md.
 */

export type Photo = {
  src: string;
  /** Размеры оригинала: без них браузер не резервирует место под снимок */
  width: number;
  height: number;
  /** Верх фигуры в пикселях оригинала */
  figTop: number;
  /** Высота фигуры в пикселях оригинала */
  figH: number;
  /** Горизонтальный центр фигуры в пикселях оригинала */
  figCx: number;
  /**
   * Какую часть фигуры показывать, если слот кадрируется по фигуре.
   * Нужна там, где человек снят длиннее остальных: аспирант помещается
   * в кадр по бёдра, студентка — по пояс. Без ограничения при равной
   * высоте фигур его голова выходит в полтора раза мельче.
   * По умолчанию — вся фигура.
   */
  figShown?: number;
  /** Точка кадрирования для круглых портретов, где работает `cover` */
  position?: string;
};

/**
 * Правило кадрирования фигуры в прямоугольном слоте: фигура занимает
 * заданную долю высоты слота и центрируется целиком. Доли, а не пиксели:
 * слот на узком экране сжимается, и пиксельные значения разъезжались бы.
 */
export type Framing = {
  /** Высота фигуры в процентах высоты слота */
  figureHPct: number;
  /** Отступ от верхней кромки слота до макушки, в процентах его высоты */
  topPct: number;
};

export type Slot = { photo: Photo; frame?: Framing };

