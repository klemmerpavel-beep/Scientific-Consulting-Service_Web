/** Коды видов сопровождения из справочника (`scripts/seed-reference.ts`). */
export const SERVICE_CODES = ['dissertation', 'postgrad', 'consulting', 'research', 'article', 'diploma'] as const;
export type ServiceCode = (typeof SERVICE_CODES)[number];

export type ServicePhase = 'start' | 'progress' | 'finish';

export const SERVICE_PHASES: readonly { readonly key: ServicePhase; readonly title: string }[] = [
  { key: 'start', title: 'Старт' },
  { key: 'progress', title: 'По ходу' },
  { key: 'finish', title: 'Сдача' },
];

export interface ServiceStep {
  /** Устойчивый ключ шага: по нему хранится отметка (Р-551). */
  readonly key: string;
  readonly phase: ServicePhase;
  readonly text: string;
}

export interface ServiceChecklist {
  /** Ключ чек-листа: `service-{код вида}`. */
  readonly key: string;
  readonly serviceCode: ServiceCode;
  readonly title: string;
  readonly when: string;
  readonly steps: readonly ServiceStep[];
}

