/**
 * Чек-листы практики (замечание владельца 08.10.2026, решение Р-494).
 *
 * Порядок основных дел по шагам: заявка, первый разговор, повторное
 * обращение, запуск работы, сдача этапа, молчание клиента, перенос срока,
 * приостановка, оплаты, передача работы, спорная ситуация, закрытие работы
 * (процессные чек-листы менеджера — Р-553); работа куратора (Р-552);
 * новый человек в команде, уход сотрудника, неделя руководителя,
 * требование субъекта персональных данных. Шаги называют кнопки и экраны
 * кабинета теми же словами, что на экранах.
 *
 * Это первая редакция: владелец просил разработать чек-листы вместе, и
 * правки к тексту приходят с кнопки замечаний. Текст — в коде, а не в
 * базе: меняется он редко и вместе с порядком работы кабинета, а правка
 * проходит проверку, как любая другая.
 *
 * Кому что видно — решает матрица прав: экран открыт куратору, менеджеру и
 * руководителю (`CHECKLIST_VIEW`, куратору — с решения Р-552); у каждого
 * чек-листа свой круг ролей, ссылки на экраны отбираются правами
 * смотрящего.
 */

import { can, ensure, type Action, type Actor } from './access.ts';
import type { AutoRule } from './checklist-auto.ts';

export type ChecklistGroup = 'clients' | 'curator' | 'team';

/** Роли, которым адресуются чек-листы: персонал практики. */
export type ChecklistRole = 'EXPERT' | 'MANAGER' | 'HEAD';

/**
 * Шаг чек-листа: текст или текст с правилом автоотметки (Р-556). Шаг с
 * правилом, открытый в контексте работы, отмечается по её состоянию.
 */
export type ChecklistStep = string | { readonly text: string; readonly auto: AutoRule };

export function stepText(step: ChecklistStep): string {
  return typeof step === 'string' ? step : step.text;
}

export function stepAuto(step: ChecklistStep): AutoRule | null {
  return typeof step === 'string' ? null : step.auto;
}

export interface Checklist {
  readonly key: string;
  readonly group: ChecklistGroup;
  readonly title: string;
  /** Повод: когда берут этот чек-лист. */
  readonly when: string;
  /** Кому он адресован. */
  readonly roles: readonly ChecklistRole[];
  readonly steps: readonly ChecklistStep[];
  /** Экраны, где делаются шаги. */
  readonly links: readonly { readonly href: string; readonly label: string; readonly action: Action }[];
}

