/** Чек-листы смотрящего: свой круг ролей, ссылки — по его правам. */
export function checklistsFor(actor: Actor): Checklist[] {
  ensure(actor, 'CHECKLIST_VIEW');
  return CHECKLISTS.filter((list) => (list.roles as readonly string[]).includes(actor.role)).map((list) => ({
    ...list,
    links: list.links.filter((link) => can(actor, link.action)),
  }));
}
