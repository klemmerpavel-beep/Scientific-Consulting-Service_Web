/** Аренда порции рассылки: строки держатся за прогоном десять минут. */
export const LEASE_MS = 10 * 60 * 1000;

/**
 * Пора ли прогону вернуть оставшиеся строки (решение Р-439). Аренда
 * ставится один раз на порцию, а ожидание почты считается по простою
 * соединения: медленный, но отвечающий сервер мог растянуть прогон за
 * десять минут — тогда следующий прогон брал неотправленный остаток той же
 * порции, и письма уходили дважды. На половине аренды прогон отпускает
 * остаток в очередь и заканчивает.
 */
export function leaseRunningOut(startedAt: number, nowMs: number): boolean {
  return nowMs - startedAt > LEASE_MS / 2;
}
