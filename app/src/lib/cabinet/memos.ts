export function memoDocx(memo: Memo): Buffer {
  const blocks: DocBlock[] = [{ kind: 'title', text: memo.title }, ...memo.points.map((text) => ({ kind: 'paragraph' as const, text: `— ${text}` }))];
  return docx(memo.title, blocks);
}
