/**
 * Ответ в шапке «Моих работ» и «Назначенных работ», когда дел за человеком
 * нет (решение Р-651).
 *
 * Приостановленная работа — действующая (решения Р-245, Р-257, Р-342), а
 * ответ строился только по идущим: клиент с приостановленной работой читал
 * «Действующих работ нет» и приглашение к новой заявке над плашкой «Работа
 * приостановлена.», куратор — «Действующих назначений нет». Теперь
 * приостановка названа прямо, как на карточке (Р-329); «Действующих … нет»
 * — когда нет ни идущих, ни приостановленных работ.
 *
 * Модуль чистый: дела и числа собирает экран, здесь — правило.
 */

export interface IdleAnswer {
  readonly lead: string;
  readonly detail: string | null;
  /** Кнопка «Новая заявка» — клиенту без действующих работ. */
  readonly request: boolean;
}

export function idleAnswer(input: {
  readonly forClient: boolean;
  /** Идущие работы. */
  readonly live: number;
  /** Приостановленные работы. */
  readonly paused: number;
  /** Ближайший срок идущих работ — строкой для клиента. */
  readonly due?: string | null;
}): IdleAnswer {
  if (input.forClient) {
    if (input.live > 0) {
      return {
        lead:
          input.live === 1
            ? 'Сейчас от вас ничего не требуется — работа идёт.'
            : 'Сейчас от вас ничего не требуется — работы идут.',
        detail: input.due ?? null,
        request: false,
      };
    }
    if (input.paused > 0) {
      return {
        lead:
          input.paused === 1
            ? 'Работа приостановлена — сейчас от вас ничего не требуется.'
            : 'Работы приостановлены — сейчас от вас ничего не требуется.',
        detail: null,
        request: false,
      };
    }
    return {
      lead: 'Действующих работ нет.',
      detail: 'Заявку на сопровождение новой работы можно оставить здесь же.',
      request: true,
    };
  }
  return {
    lead: 'Сейчас ход не за вами.',
    detail:
      input.live > 0
        ? 'Этапы ваших работ сданы менеджеру, ждут клиента, ещё не запущены или закрыты; менеджер сообщит, когда продолжать.'
        : input.paused === 1
          ? 'Ваша работа приостановлена: менеджер сообщит, когда продолжать.'
          : input.paused > 1
            ? 'Ваши работы приостановлены: менеджер сообщит, когда продолжать.'
            : 'Действующих назначений нет.',
    request: false,
  };
}
