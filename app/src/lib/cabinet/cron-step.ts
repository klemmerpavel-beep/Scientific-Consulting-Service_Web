/**
 * Шаг планового прогона рассылки (решение Р-438).
 *
 * Перед отправкой прогон ставит в очередь сроки, напоминания и сводки —
 * восемь шагов подряд. Прежде любой из них, падая каждый раз, останавливал
 * и отправку: писем не уходило до исправления, хотя очередь была полна.
 * Теперь сбой шага пишется в журнал сервера и в ответ прогона, а
 * следующие шаги и отправка идут своим порядком.
 */
export async function cronStep(name: string, run: () => Promise<number>, failed: string[]): Promise<number> {
  try {
    return await run();
  } catch (error) {
    console.error(`[outbox] шаг «${name}» не выполнен`, error);
    failed.push(name);
    return 0;
  }
}
