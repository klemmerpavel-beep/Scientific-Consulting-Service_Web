/**
 * Письмо заявителю, которому отказали (решение Р-217).
 *
 * Модуль намеренно не знает ни о базе, ни о сети — как и `events.ts`: здесь
 * решается, что уходит человеку за пределы сервера, и проверять это надо
 * без поднятой базы.
 */

import { PRACTICE_EMAIL, PRACTICE_PHONE } from '../practice-contacts.ts';
import { siteUrl } from '../site-url.ts';
import { CHANNEL_OFF } from './events.ts';

/**
 * Текст письма об отказе. Отдельной функцией — его проверяют без базы.
 *
 * Письмо отвечает на обращение, а не утешает: называет тему, говорит
 * «взяться не можем», приводит причину словами менеджера и оставляет
 * дверь открытой. Ссылки входа нет — кабинета у человека нет.
 */
export function declineLetter(
  name: string | null,
  topic: string | null,
  reason: string,
): { subject: string; body: string } {
  const base = siteUrl();
  const greeting = name === null || name.trim().length === 0 ? 'Здравствуйте.' : `Здравствуйте, ${name.trim()}.`;
  const about = topic === null || topic.trim().length === 0 ? '' : ` по теме «${topic.trim()}»`;
  return {
    subject: 'Ответ на заявку ProDisser',
    body:
      `${greeting}\n` +
      `Спасибо за обращение${about}. Взяться за эту работу мы не можем.\n` +
      `Причина: ${reason}\n` +
      (base === null
        ? 'Если обстоятельства изменятся, оставьте новую заявку на сайте ProDisser.'
        : `Если обстоятельства изменятся, оставьте новую заявку на сайте: ${base}.`),
  };
}

/**
 * Письмо «Заявка получена» (требование Т-05, решение Р-312).
 *
 * Тишина после заявки выглядит как потерянная заявка. Письмо говорит, что
 * будет дальше, называет срок ответа и контакты практики. Адрес в заявке
 * с сайта не подтверждён: имени, темы и ссылок в письме нет (Р-252) — оно
 * одинаково для любого адреса и чужой текст разослать через него нельзя.
 * Ссылки входа нет: кабинета у заявителя ещё нет.
 */
export function receivedLetter(): { subject: string; body: string } {
  return {
    subject: 'Заявка получена — ProDisser',
    body:
      'Здравствуйте.\n' +
      'Ваша заявка получена. Куратор разберёт её и ответит в течение рабочего дня; решение придёт письмом на этот адрес.\n' +
      `Связаться с нами: ${PRACTICE_EMAIL}, ${PRACTICE_PHONE}.\n` +
      'Если вы не оставляли заявку, удалите это письмо.',
  };
}

/**
 * Письмо об отказе для конкретной заявки (решение Р-252).
 *
 * Заявка с сайта приходит с открытой формы, и адрес в ней никем не
 * подтверждён: вписать можно чужой ящик. Имя и тема из такой заявки в
 * письмо не подставляются — иначе отказ становился способом разослать
 * произвольный текст («Здравствуйте, <ссылка>») на чужой адрес от имени
 * практики. Обращение обезличенное, причина — словами менеджера.
 *
 * Заявка из кабинета подана вошедшим человеком, и письмо уходит на адрес
 * его учётной записи, подтверждённый входом по ссылке: ему имя и тема
 * возвращаются как есть.
 */
export function declineLetterFor(
  lead: { readonly source: string; readonly name: string | null; readonly topic: string | null },
  reason: string,
): { subject: string; body: string } {
  return lead.source === 'cabinet'
    ? declineLetter(lead.name, lead.topic, reason)
    : declineLetter(null, null, reason);
}

/** Адрес почты из заявки; `null`, если человек оставил телефон. */
export function leadAddress(lead: { contactKind: string; contact: string }): string | null {
  const contact = lead.contact.trim();
  return lead.contactKind === 'email' && /^[^\s@]+@[^\s@]+$/u.test(contact) ? contact : null;
}

/** Письмо об отказе, как его видит очередь. */
export interface DeclineLetterRow {
  readonly state: 'PENDING' | 'SENT' | 'FAILED' | 'EXPIRED';
  readonly lastError: string | null;
}

/**
 * Что стало с ответом заявителю — строка для экрана заявки.
 *
 * Менеджер, отклонивший заявку, должен видеть, дошёл ли ответ: иначе
 * причина снова оседает в базе, как до решения Р-217, только теперь без
 * ведома того, кто её написал. Дата отправки добавляется экраном.
 */
export function declineLetterNote(
  lead: { contactKind: string; contact: string },
  letter: DeclineLetterRow | null,
): string {
  if (letter === null) {
    return leadAddress(lead) === null
      ? 'Письма нет: заявитель оставил телефон, причину сообщают звонком.'
      : 'Письмо не ставилось: заявка была помечена как машинная либо отклонена до 24.09.2026, когда отказ ещё не уходил письмом.';
  }
  if (letter.state === 'SENT') return 'Письмо с причиной ушло заявителю';
  // Письмо об отказе сроком не ограничено (`lifetimeMs`); ветка — на случай,
  // если правило годности когда-нибудь его коснётся.
  if (letter.state === 'EXPIRED') return 'Письмо устарело в очереди и не отправлено.';
  if (letter.state === 'FAILED') {
    // Повтор — кнопкой на карточке заявки (требование М-19, решение Р-307).
    return `Письмо не доставлено: ${letter.lastError ?? 'причина не записана'}. Исправьте адрес в сведениях заявки и отправьте ещё раз.`;
  }
  return letter.lastError === CHANNEL_OFF
    ? 'Письмо ждёт почтового канала и уйдёт, когда почта будет настроена.'
    : 'Письмо стоит в очереди на отправку.';
}
