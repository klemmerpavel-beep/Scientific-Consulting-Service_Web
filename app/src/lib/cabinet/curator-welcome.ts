/**
 * Первый вход куратора и экран без договора поручения (требование Э-12,
 * решение Р-331).
 *
 * Куратор без договора видел «Доступ к материалам ещё не открыт… напишите
 * руководителю» — и не знал, как написать: переписки у него нет (Р-150).
 * Теперь на экране кнопка «Сообщить руководителю»: руководитель получает
 * уведомление и дело на «Сегодня». Блок первого входа говорит, где ход за
 * куратором, как сдать этап и как спросить менеджера, и называет два
 * правила работы.
 *
 * Модуль чистый: тексты и правило частоты проверяются без базы.
 */

import type { Letter } from './curator-letters.ts';

/** «Сообщить руководителю» — не чаще раза в сутки (Д-8 плана куратора). */
export const NDA_REQUEST_PAUSE_MS = 24 * 60 * 60 * 1000;

/** Можно ли сообщить снова: прошлое сообщение старше суток или его не было. */
export function ndaRequestOpen(requestedAt: Date | null, at: Date): boolean {
  return requestedAt === null || at.getTime() - requestedAt.getTime() >= NDA_REQUEST_PAUSE_MS;
}

/** Блок первого входа куратора: три строки, два правила. */
export const CURATOR_WELCOME = {
  title: 'Как устроен кабинет куратора',
  lines: [
    'Где ход за вами — в верхней строке «Назначенных работ»: главное дело и кнопка на его экран.',
    'Как сдать этап — на экране этапа: приложите свою версию и нажмите «Сдать этап менеджеру» с запиской.',
    'Вопрос по заданию — письмом менеджеру работы, почта — в «О работе» на карточке работы.',
  ],
  rules: [
    'Автор работы — клиент: вы разбираете, комментируете и редактируете его текст.',
    'Общение с клиентом — только в кабинете.',
  ],
} as const;

/**
 * Письмо руководителю «Куратор {ФИО} ждёт договор поручения». Почта
 * куратора — чтобы связаться для подписания; данных клиентов нет.
 */
export function ndaWaitingLetter(curator: { readonly fullName: string; readonly email: string }, works: number): Letter {
  return {
    subject: `Куратор ${curator.fullName} ждёт договор поручения`,
    body:
      `Куратор ${curator.fullName} (${curator.email}) сообщает, что ждёт договор поручения обработки ` +
      'персональных данных: без него материалы клиентов ему закрыты.\n' +
      (works === 0
        ? 'Назначенных действующих работ у него пока нет.\n'
        : `Назначенных действующих работ: ${works}.\n`) +
      'Отметить договор можно в «Учётных записях», раздел «Договоры поручения обработки данных».',
  };
}
