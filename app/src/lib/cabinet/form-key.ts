/**
 * Одноразовый ключ формы — часть без базы (аудит 15.11.2026, находка Ф-9;
 * решение Р-934).
 *
 * Форма несёт случайный ключ в скрытом поле. Дубль вкладки, кнопка «назад»
 * и повтор запроса при обрыве связи отправляют ту же форму с тем же
 * ключом — действие занимает ключ перед записью (`form-once.ts`), и вторая
 * отправка получает отказ вместо второй записи. Две формы, открытые
 * порознь, несут разные ключи: это два намеренных действия.
 */

import { randomBytes } from 'node:crypto';

/** Имя скрытого поля формы. */
export const FORM_KEY_FIELD = 'formKey';

/** Сколько живёт занятый ключ: дольше форма открытой не лежит. */
export const FORM_KEY_TTL_MS = 2 * 24 * 60 * 60 * 1000;

/** Что читает человек, отправивший ту же форму второй раз. */
export const FORM_REPLAY = 'Эта форма уже отправлена, запись сделана первой отправкой: обновите страницу и проверьте её';

/** Новый ключ: 128 случайных бит шестнадцатеричной записью. */
export function newFormKey(): string {
  return randomBytes(16).toString('hex');
}

/**
 * Ключ из поля формы. `null` — ключа нет или он не того вида: такая
 * отправка идёт без защиты, а не отклоняется — форма могла быть открыта до
 * выката.
 */
export function formKeyOf(value: unknown): string | null {
  return typeof value === 'string' && /^[0-9a-f]{32}$/u.test(value) ? value : null;
}
