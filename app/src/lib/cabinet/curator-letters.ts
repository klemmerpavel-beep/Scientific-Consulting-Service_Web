/**
 * Письма куратору: кабинет открыт, доступ к материалам открыт, назначение
 * на работу (требование Э-03, решение Р-323).
 *
 * Без этих писем куратор не знал, что кабинет существует и что в нём
 * появилась работа. Каждое письмо несёт кнопку «Открыть кабинет» — путь
 * задаёт вызывающий через `path` строки очереди (Т-06, Р-309). Ссылки
 * входа в письме нет (Р-162): кабинет просит адрес почты и присылает
 * ссылку сам.
 *
 * Модуль чистый: ни базы, ни часов — проверяется встроенным `node --test`.
 */

import { formatDay } from './approval-text.ts';

export interface Letter {
  readonly subject: string;
  readonly body: string;
}

/** Абзац о договоре поручения: зачем он и кто его оформляет. */
const NDA_REASON =
  'Материалы клиентов откроются после договора поручения обработки персональных данных ' +
  '(ч. 3 ст. 6 Федерального закона № 152-ФЗ). Его оформляет руководитель практики; ' +
  'когда договор будет отмечен, придёт письмо «Доступ к материалам открыт».';

/**
 * «Вам открыт кабинет куратора ProDisser» — при заведении учётной записи
 * куратора или при смене роли на куратора. Если договор поручения уже
 * отмечен, абзаца о нём нет.
 */
export function invitationLetter(ndaSigned: boolean): Letter {
  return {
    subject: 'Вам открыт кабинет куратора ProDisser',
    body: [
      'Вам открыт личный кабинет куратора ProDisser.',
      '',
      'В кабинете — назначенные вам работы: задание и срок каждого этапа, материалы клиента, ' +
        'ваши версии и замечания, вознаграждение.',
      '',
      'Как войти: нажмите «Открыть кабинет» и укажите адрес этой почты — ссылка для входа придёт ' +
        'письмом. Пароля нет.',
      ...(ndaSigned ? [] : ['', NDA_REASON]),
    ].join('\n'),
  };
}

/** «Доступ к материалам открыт» — при первой отметке договора поручения. */
export function ndaSignedLetter(): Letter {
  return {
    subject: 'Доступ к материалам открыт',
    body:
      'Руководитель практики отметил договор поручения обработки персональных данных.\n' +
      'Материалы назначенных вам работ открыты в личном кабинете.',
  };
}

export interface AssignedWork {
  readonly code: string;
  readonly title: string;
  readonly topic: string | null;
  readonly serviceType: string;
  readonly dueOn: Date | null;
  readonly manager: string;
}

/**
 * «Вас назначили куратором работы {код}».
 *
 * С договором поручения — тип сопровождения, название и тема, срок,
 * менеджер. Без договора — тип, срок и менеджер: название и тема пишутся
 * клиентом и нередко называют предмет его исследования и организацию,
 * поэтому до договора не передаются (ответ владельца ОЭ-5; Р-237, Р-301).
 * ФИО клиента нет ни в одном случае.
 */
export function assignmentLetter(work: AssignedWork, ndaSigned: boolean): Letter {
  const due = work.dueOn === null ? 'не назначен' : formatDay(work.dueOn);
  const common = [
    `Тип сопровождения: ${work.serviceType}.`,
    `Срок работы: ${due}.`,
    `Менеджер: ${work.manager}.`,
  ];
  const topic = (work.topic ?? '').trim();
  return {
    subject: `Вас назначили куратором работы ${work.code}`,
    body: ndaSigned
      ? [
          `${work.code} — ${work.title}.`,
          ...(topic === '' || topic === work.title ? [] : [`Тема: ${topic}.`]),
          ...common,
          '',
          'Задание, срок этапа и материалы клиента — в личном кабинете.',
        ].join('\n')
      : [
          `Работа ${work.code}.`,
          ...common,
          '',
          'Доступ к материалам откроется после договора поручения обработки персональных данных.',
        ].join('\n'),
  };
}
