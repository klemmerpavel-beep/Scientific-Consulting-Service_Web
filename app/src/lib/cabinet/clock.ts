/**
 * «Сегодня» для того, что кабинет показывает.
 *
 * Просрочка днями, окна «за квартал» и «ближайшие две недели», срок
 * «прошёл» — всё это читается от текущего дня. Наполнение базы снимков
 * отсчитывает даты от постоянной точки (`REFERENCE` в
 * `scripts/seed-artboards.ts`), а экраны считали от настоящего «сейчас»:
 * снимок, снятый во вторник, расходился со снятым в среду одними только
 * числами дней, и разбор изменений показывал шум вместо правок облика
 * (решение Р-205).
 *
 * Переменная `CABINET_NOW` задаёт день явно. Её выставляют только
 * инструменты съёмки и только при базе снимков; в бою она не действует,
 * и часы идут настоящие. Сроки сессий, ссылок и очереди уведомлений
 * через этот модуль не ходят: там ошибка в часах стала бы дырой, а не
 * неточностью подписи. Исключение — отметка последнего входа: она только
 * подпись на экране (решение Р-217).
 */

/**
 * Остановленные часы на боевой базе заморозили бы все просрочки, и
 * экраны тихо показывали бы неправду. Поэтому `CABINET_NOW` действует
 * только при базе снимков — той, в адресе которой есть слово «artboard»;
 * то же условие ставят наполнение и съёмка (решение Р-214).
 */
function fixedAllowed(): boolean {
  return /artboard/iu.test(process.env.DATABASE_URL ?? '');
}

export function now(): Date {
  const fixed = process.env.CABINET_NOW;
  if (fixed !== undefined && fixed !== '' && fixedAllowed()) {
    const at = Date.parse(fixed);
    if (!Number.isNaN(at)) return new Date(at);
  }
  return new Date();
}

/**
 * Сегодняшний день по Москве как полночь UTC — в том виде, в каком формы
 * кабинета хранят даты без времени (`2026-09-26T00:00:00Z`).
 *
 * Момент берётся из той же `now()`, что у остальных экранов: снимки с
 * остановленными часами получают тот же день, что и прочие подписи.
 * Прежде функция жила в `admin.ts`, а сроки сравнивались то с текущим
 * моментом, то с началом UTC-суток: с полуночи до трёх часов ночи по
 * Москве вчерашний срок ещё не считался прошедшим, а один и тот же срок
 * на главной и в отчёте числился по-разному (решение Р-257).
 */
// Форматы создаются один раз: создание стоит сотни микросекунд, а день
// по Москве считается на каждую заявку, этап и сообщение (решение Р-474).
const MOSCOW_DAY = new Intl.DateTimeFormat('en-CA', {
  timeZone: 'Europe/Moscow',
  year: 'numeric',
  month: '2-digit',
  day: '2-digit',
});
const MOSCOW_HOUR = new Intl.DateTimeFormat('en-GB', { timeZone: 'Europe/Moscow', hour: '2-digit', hourCycle: 'h23' });

export function moscowToday(at: Date = now()): Date {
  return new Date(`${MOSCOW_DAY.format(at)}T00:00:00Z`);
}

/** Час по Москве, 0–23 (улучшение УК-14, решение Р-393). */
export function moscowHour(at: Date = now()): number {
  return Number(MOSCOW_HOUR.format(at));
}

/**
 * С какого часа по Москве уходят плановые письма дня: напоминания о
 * сроках, автозакрытие, сводка и сигналы (улучшение УК-14, решение
 * Р-393). Прежде они уходили в первую минуту суток — ночью.
 */
export const DAILY_MAIL_HOUR = 9;

/**
 * Прошёл ли срок: день срока раньше сегодняшнего дня по Москве. Срок —
 * день, и в самый день срока он ещё не прошёл (решения Р-240, Р-257).
 */
export function isPastDue(dueOn: Date | null | undefined, at: Date = now()): boolean {
  if (dueOn === null || dueOn === undefined) return false;
  return dueOn.getTime() < moscowToday(at).getTime();
}

/**
 * Сколько дней прошло после срока; `null` — срок не наступил. Счёт — от
 * начала сегодняшнего дня по Москве, как у всех «срок прошёл» кабинета
 * (решение Р-257).
 */
export function daysPast(dueOn: Date | null | undefined, at: Date = now()): number | null {
  if (dueOn === null || dueOn === undefined) return null;
  // Срок — день: он хранится полночью UTC, и счёт идёт от этого дня, а
  // не от часа, если время в значении всё же оказалось.
  const due = Math.floor(dueOn.getTime() / 86_400_000) * 86_400_000;
  const days = Math.round((moscowToday(at).getTime() - due) / 86_400_000);
  return days > 0 ? days : null;
}
