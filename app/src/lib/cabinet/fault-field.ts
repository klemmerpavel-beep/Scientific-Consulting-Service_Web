/**
 * Поле, к которому относится отказ действия (аудит 15.11.2026, находка
 * Д-2; решение Р-936).
 *
 * Отказ службы — фраза для человека: «Укажите дату поступления», «Срок
 * этапа переносится с причиной». Экран показывал её блоком над формой, а
 * само поле оставалось без признака ошибки: читалка, дойдя до него,
 * не называла ни того, что значение не принято, ни причины.
 *
 * Службы поля не называют и называть не должны: они не знают, какой
 * формой вызваны. Поле определяет действие — оно знает свою форму. Способ
 * намеренно узкий: отказ относится к полю, только если его фраза называет
 * предмет поля («причина», «дата», «сумма»). Отказ о состоянии — «этап
 * уже согласован», «транш оплачен» — предмета не называет, и поле
 * остаётся без пометки: ложный признак ошибки хуже его отсутствия.
 */

export type FaultKind = 'reason' | 'date' | 'amount' | 'email' | 'title' | 'text' | 'month' | 'person';

/** По какой основе слова отказ узнаёт предмет поля. */
const STEM: Readonly<Record<FaultKind, RegExp>> = {
  reason: /причин|основани/iu,
  date: /(?:^|[^а-яё])(?:дат[аеуыой]|срок)/iu,
  amount: /сумм|стоимост|оплачено|оплат[аеуы]/iu,
  email: /почт|адрес/iu,
  title: /назван/iu,
  text: /сообщени|комментари|замечани/iu,
  month: /месяц/iu,
  person: /заказчик|фамили|имя/iu,
};

/** Идентификатор блока отказа: цель `aria-describedby` поля. Отказ на экране один. */
export const FAULT_ID = 'action-fault';

/** Идентификатор поля в разметке — те же знаки, что у `fieldId` формы. */
export const FAULT_FIELD = /^[A-Za-z][A-Za-z0-9_-]{0,63}$/u;

/**
 * Идентификатор поля, о котором говорит отказ, или ничего.
 *
 * `fields` — поля формы в порядке старшинства: «Срок этапа переносится с
 * причиной» называет и срок, и причину, а не хватает причины — она в
 * перечне первой.
 */
export function faultField(
  reason: string,
  fields: Readonly<Record<string, FaultKind>>,
): string | undefined {
  for (const [id, kind] of Object.entries(fields)) {
    if (FAULT_FIELD.test(id) && STEM[kind].test(reason)) return id;
  }
  return undefined;
}
