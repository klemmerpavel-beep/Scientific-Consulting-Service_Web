/**
 * Базовый адрес сайта из окружения, приведённый к одному виду.
 *
 * Адрес нужен трём местам: metadataBase в разметке страниц, ссылка на карту
 * сайта в robots.txt и абсолютные адреса в самой карте. Каждое из них читало
 * переменную самостоятельно и по-разному вело себя, когда её не задали:
 * robots строку карты опускал, а карта отдавала относительные адреса вида
 * `/main`. Относительный адрес в sitemap.xml недопустим — файл считается
 * некорректным целиком, и поисковик не берёт из него ни одной страницы.
 *
 * Здесь одно правило на всех: либо есть разобранный абсолютный адрес без
 * завершающей косой черты, либо null, и вызывающий сам решает, что делать.
 */
export function siteUrl(): string | null {
  const raw = process.env.NEXT_PUBLIC_SITE_URL?.trim();
  if (!raw) return null;
  try {
    const url = new URL(raw);
    return url.origin + url.pathname.replace(/\/+$/, '');
  } catch {
    // Опечатка в переменной не должна ронять сборку: ведём себя как при
    // незаданном адресе, а не отдаём наружу битые ссылки.
    return null;
  }
}
