export default async function ToolsScreen() {
  const actor = await requireActor('/cabinet/manage/tools');

  // «Управление» — у всех сотрудников (указание владельца 12.10.2026,
  // решение Р-559): первым блоком — чек-листы и материалы, ниже — разделы,
  // открытые роли. Куратору разделов нет, и экран — только материалы.
  if (!hasToolsScreen(actor)) redirect(homeFor(actor));
  const allowed = TOOLS.filter((tool) => can(actor, tool.action));
  const materials = staffMaterials(actor, await ownerTemplates(actor));
  if (allowed.length === 0 && materials.length === 0) redirect(homeFor(actor));
  const head = actor.role === 'HEAD';

  const groups = GROUPS.map((group) => ({
    ...group,
    tools: allowed
      .filter((tool) => tool.group === group.key)
      .slice()
      .sort((a, b) => OFTEN_ORDER[a.often] - OFTEN_ORDER[b.often]),
  })).filter((group) => group.tools.length > 0);

  return (
    <Shell actor={actor} current="/cabinet/manage/tools">
      <ScreenHead
        title="Управление"
        note={
          head
            ? 'Чек-листы и материалы, а также всё, что не входит в ежедневную работу с заказами: настройка практики, надзорные журналы и перенос истории. Блоки свёрнуты — откройте нужный.'
            : 'Чек-листы и материалы: открываются на экране и скачиваются файлом Word.'
        }
      />

      {/* Чек-листы и материалы — первым блоком, со скачиванием (Р-559).
          Блоки экрана свёрнуты и раскрываются по нажатию: все сразу
          перегружали страницу, а с первого дня нужны не все (замечание
          владельца 13.10.2026, решение Р-572). Распорядок дня «Как этим
          пользоваться» (Р-201) снят тем же замечанием: порядок задают
          метки частоты у разделов. */}
      {materials.length === 0 ? null : groups.length === 0 ? (
        // У куратора разделов нет, материалы — весь экран: сворачивать
        // единственный блок незачем.
        <MaterialsList
          id="materials"
          title="Чек-листы и материалы"
          note="Открыть — экран кабинета; файлы — в Word. Чтобы сохранить экран в PDF, напечатайте его: Ctrl + P, на Mac ⌘ + P, — и выберите «Сохранить в PDF»."
          rows={materials}
        />
      ) : (
        <FoldCard
          id="materials"
          title="Чек-листы и материалы"
          note="Открыть — экран кабинета; файлы — в Word. Чтобы сохранить экран в PDF, напечатайте его: Ctrl + P, на Mac ⌘ + P, — и выберите «Сохранить в PDF»."
          count={`${materials.length} ${plural(materials.length, 'материал', 'материала', 'материалов')}`}
        >
          <MaterialRows rows={materials} />
        </FoldCard>
      )}

      {groups.map((group) => (
        // Группа — свёртка `details`, а не `section`: сценарий движения
        // сайта забирает `main > section` и дописывает плашкам задержку
        // появления прямо в разметку (решения Р-186, Р-192).
        <FoldCard
          key={group.key}
          title={group.title}
          note={group.note}
          count={`${group.tools.length} ${plural(group.tools.length, 'раздел', 'раздела', 'разделов')}`}
        >
          <ul
            style={{
              margin: 0,
              padding: 0,
              listStyle: 'none',
              display: 'grid',
              // Не больше двух плашек в ряду: третья ужимает строки до
              // разрыва посреди слова (решение Р-189).
              gridTemplateColumns: 'repeat(auto-fill, minmax(min(420px,100%),1fr))',
              gap: 16,
              maxWidth: 'calc(2 * 560px + 16px)',
            }}
          >
            {group.tools.map((tool) => (
              <Card as="li" key={tool.href} link>
                <div
                  style={{
                    display: 'flex',
                    gap: 12,
                    alignItems: 'baseline',
                    justifyContent: 'space-between',
                    marginBottom: 4,
                  }}
                >
                  {/* Ссылка растянута на плашку, как на плашках внимания:
                      подсвечивается плашка целиком, и нажиматься должна
                      она же, а не строка названия (решения Р-209, Р-253). */}
                  <Heading level={3} size={3}>
                    <a className="cab-stretch" href={tool.href}>{tool.title}</a>
                  </Heading>
                  <Chip nowrap>{tool.often}</Chip>
                </div>
                <Text muted size={14} style={{ marginBottom: 8 }}>
                  {tool.note}
                </Text>
                {/* Повод: заказчик писал, что логика экрана непонятна и
                    неясно, как с ним работать. Назначение раздела само по
                    себе на это не отвечает — отвечает случай, по которому
                    сюда идут (решение Р-201). */}
                <Text muted size={13}>
                  Заходят, когда: {tool.when}
                </Text>
              </Card>
            ))}
          </ul>
        </FoldCard>
      ))}
    </Shell>
  );
}
