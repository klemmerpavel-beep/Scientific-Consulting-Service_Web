/**
 * Параметры, которые не меняют содержимого страницы: метки рекламы и
 * отметки перехода Яндекса (Р-776). Объявления Директа ведут на `/main` и
 * `/students` с `utm_*`, Директ дописывает `yclid`, браузер Яндекса —
 * `ysclid`; без `Clean-param` каждый переход — отдельный адрес той же
 * страницы, и Вебмастер считает их дублями. canonical склеивает их тоже,
 * но для Яндекса это подсказка, а `Clean-param` — правило. Директива
 * межсекционная: Яндекс читает её из любой группы, прочие роботы её
 * пропускают.
 */
export const CLEAN_PARAMS = ['utm_source', 'utm_medium', 'utm_campaign', 'utm_content', 'utm_term', 'yclid', 'ysclid'];

/**
 * Тело robots.txt.
 *
 * Обработчиком `route.ts`, а не файлом `robots.ts`: у описания robots в
 * Next.js нет поля для `Clean-param` (Р-776). Правила прежние. Отдельным
 * модулем — потому что файл маршрута выгружает только `GET` и настройки
 * сегмента, а тест читает правила отсюда.
 */
export function robotsTxt(env: { demoStand: boolean; base: string | null }): string {
  // Демонстрационный стенд закрывается целиком: временный адрес не должен
  // попасть в выдачу и перебить будущий боевой.
  if (env.demoStand) return 'User-Agent: *\nDisallow: /\n';

  const lines = [
    'User-Agent: *',
    'Allow: /',
    'Disallow: /api/',
    // Кабинет закрыт вторым рубежом: мета-тег `noindex` стоит в разметке
    // раздела, но робот, читающий только robots.txt, о нём не узнает.
    // Страница входа `/cabinet` открыта для обхода намеренно: робот должен
    // увидеть её `noindex`, иначе Google показывает закрытый адрес в
    // выдаче без описания (Р-776).
    'Disallow: /cabinet/',
    // `/cabinet-preview/` — прототип кабинета, открытый по ссылке для
    // приёмки (решение Р-174). Правило `/cabinet/` его не покрывает: это
    // другой путь. В выдаче ему делать нечего — снимки экранов перебили бы
    // настоящие страницы сайта.
    'Disallow: /cabinet-preview/',
    `Clean-param: ${CLEAN_PARAMS.join('&')}`,
  ];
  if (env.base) lines.push('', `Sitemap: ${env.base}/sitemap.xml`);
  return lines.join('\n') + '\n';
}
