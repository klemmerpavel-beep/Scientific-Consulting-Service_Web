#!/bin/sh
# Зеркало практики на Яндекс Диске. Ставится в cron на хосте:
#   0 * * * * /opt/prodisser/deploy/yandex-sync.sh >> /var/log/prodisser-yandex.log 2>&1
#
# Раз в час на Диск уходят таблицы реестров и файлы материалов. Таблицы
# перезаписываются целиком — это всегда полный список, а не приращение;
# файлы сверяются по описи, и на Диск идёт только изменившееся.
#
# ПОЧЕМУ ЯНДЕКС, А НЕ GOOGLE. В таблицах и материалах персональные данные.
# Выгрузка их в Google означала бы трансграничную передачу в страну, которой
# нет в перечне обеспечивающих адекватную защиту: отдельное согласие каждого
# субъекта, уведомление Роскомнадзора до начала передачи и новая редакция
# Политики. Серверы Яндекса — в России, передачи за границу нет (Р-155).
#
# ЧТО ТРЕБУЕТСЯ ДО ВКЛЮЧЕНИЯ. Хранилище — третье лицо, и обработка ему
# поручается по договору (ч. 3 ст. 6 152-ФЗ). Годится тариф для организаций,
# где такой договор есть; личный Диск не годится. Перечень поручений в
# Политике дополняется пунктом об облачном хранилище — это правка
# юридического текста, она идёт через юриста. До этого поля в deploy/.env
# остаются пустыми, и зеркало молча ничего не делает: оно выключено, а не
# сломано.
#
# Этот скрипт заменяет прежний yandex-upload.sh: тот выгружал две таблицы в
# корень папки, этот — семь таблиц, файлы материалов и опись. Строку прежнего
# скрипта из расписания нужно убрать, иначе в папке будут лежать две пары
# таблиц: свежая в «Таблицы/» и старая в корне.

set -eu
DIR="$(cd "$(dirname "$0")" && pwd)"
COMPOSE="docker compose --env-file $DIR/.env -f $DIR/docker-compose.yml"

say() { echo "$(date -Is) $*"; }

# Значение читается построчно, а не через `. .env`: в файле есть строки с
# угловыми скобками (SMTP_FROM), которые оболочка приняла бы за
# перенаправление ввода.
read_env() {
  sed -n "s/^$1=//p" "$DIR/.env" 2>/dev/null | head -n 1 | tr -d '\r' \
    | sed -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'$/\1/"
}

if [ -z "$(read_env YANDEX_DISK_USER)" ] || [ -z "$(read_env YANDEX_DISK_PASSWORD)" ]; then
  say "зеркало на Диске выключено: YANDEX_DISK_USER или YANDEX_DISK_PASSWORD не задан в deploy/.env"
  exit 0
fi

# Два прогона разом означали бы две описи, спорящие друг с другом. Замок
# снимается сам при завершении: флаг -n не ждёт, а выходит.
LOCK="$DIR/.yandex-sync.lock"
if command -v flock > /dev/null 2>&1; then
  exec 9> "$LOCK"
  if ! flock -n 9; then
    say "прошлый прогон ещё идёт — пропускаем этот час"
    exit 0
  fi
fi

# Служебный образ поднимается на один запуск и гаснет (Р-132): в рабочем
# образе ни исходников, ни каталога scripts нет.
if ! $COMPOSE --profile tools run --rm -T tools scripts/yandex-sync.ts; then
  say "ОШИБКА: зеркало не обновилось"
  exit 1
fi
