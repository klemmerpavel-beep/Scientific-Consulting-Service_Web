#!/bin/sh
# Мост «Диск → база»: книга заказов с Яндекс Диска переезжает в кабинет.
# Ставится в cron на хосте, со сдвигом от зеркала — чтобы два прогона не
# спорили за один служебный контейнер:
#   30 * * * * /opt/prodisser/deploy/book-pull.sh >> /var/log/prodisser-book.log 2>&1
#
# Раз в час книга скачивается с Диска, разбирается тем же кодом, что и на
# экране переноса, и строки без замечаний фиксируются. Строка с ошибкой
# разбора остаётся в предпросмотре и ждёт человека: молча угадывать за него
# нельзя (решение Р-202).
#
# Повторная загрузка того же файла не делает ничего: свёртка файла
# сверяется с прежними зафиксированными загрузками, и разбор даже не
# начинается.
#
# ЧТО ТРЕБУЕТСЯ ДО ВКЛЮЧЕНИЯ. Доступ к Диску — те же YANDEX_DISK_USER и
# YANDEX_DISK_PASSWORD, что у зеркала, плюс BOOK_PULL_PATH — путь книги
# внутри папки практики, например «Отработка заказов.xlsx». Пока путь не
# задан, мост молча ничего не делает: он выключен, а не сломан.
#
# ЦЕЛЕВОЕ УСТРОЙСТВО ОБРАТНОЕ. Заказы ведутся в кабинете, а таблица на
# Диске остаётся выгрузкой — её пишет yandex-sync.sh. Мост нужен на
# переходное время, пока учёт ведётся книгой; когда он закончится, строку
# из расписания убирают.

set -eu
DIR="$(cd "$(dirname "$0")" && pwd)"
COMPOSE="docker compose --env-file $DIR/.env -f $DIR/docker-compose.yml"

say() { echo "$(date -Is) $*"; }

# Значение читается построчно, а не через `. .env`: в файле есть строки с
# угловыми скобками (SMTP_FROM), которые оболочка приняла бы за
# перенаправление ввода.
read_env() {
  sed -n "s/^$1=//p" "$DIR/.env" 2>/dev/null | head -n 1 | tr -d '\r' \
    | sed -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'$/\1/"
}

if [ -z "$(read_env YANDEX_DISK_USER)" ] || [ -z "$(read_env YANDEX_DISK_PASSWORD)" ]; then
  say "мост «Диск → база» выключен: YANDEX_DISK_USER или YANDEX_DISK_PASSWORD не задан в deploy/.env"
  exit 0
fi
if [ -z "$(read_env BOOK_PULL_PATH)" ]; then
  say "мост «Диск → база» выключен: BOOK_PULL_PATH не задан в deploy/.env"
  exit 0
fi

# Два прогона разом завели бы две загрузки по одной книге. Замок снимается
# сам при завершении: флаг -n не ждёт, а выходит.
LOCK="$DIR/.book-pull.lock"
if command -v flock > /dev/null 2>&1; then
  exec 9> "$LOCK"
  if ! flock -n 9; then
    say "прошлый прогон ещё идёт — пропускаем этот час"
    exit 0
  fi
fi

# Служебный образ поднимается на один запуск и гаснет (Р-132): в рабочем
# образе ни исходников, ни каталога scripts нет.
if ! $COMPOSE --profile tools run --rm -T tools scripts/book-pull.ts; then
  say "ОШИБКА: книга не перенесена"
  exit 1
fi
