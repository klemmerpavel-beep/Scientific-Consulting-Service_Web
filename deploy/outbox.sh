#!/bin/sh
# Рассылка накопившихся уведомлений кабинета. Ставится в cron на хосте
# выкатом (cron-sync.sh, Р-262):
#   * * * * * /opt/prodisser/deploy/outbox.sh >> /var/log/prodisser-outbox.log 2>&1
#
# Раз в минуту, а не раз в час: уведомление «этап ждёт материалов» теряет
# смысл тем быстрее, чем дольше идёт. Пустой вызов стоит одного запроса к базе.
#
# Отдельный скрипт, а не строка с curl прямо в crontab: маршрут закрыт общим
# секретом, а cron не читает deploy/.env — подстановка $CABINET_CRON_SECRET
# в crontab дала бы пустой заголовок и отказ маршрута при внешне исправном
# расписании.

set -eu
DIR="$(cd "$(dirname "$0")" && pwd)"
URL="http://127.0.0.1:3000/cabinet/api/outbox"

# Секрет берётся одной строкой, а не через `. .env`: в файле есть значения
# с угловыми скобками (SMTP_FROM=ProDisser <site@prodisser.ru>), и оболочка
# приняла бы их за перенаправление ввода.
#
# Удаляется только возврат каретки (файл могли править в Windows) и кавычки
# по краям значения. Скопом через `tr -d` их снимать нельзя: tr удаляет
# перечисленные знаки по всей строке, и секрет base64 лишился бы каждой
# буквы, попавшей в набор, — заголовок перестал бы совпадать.
SECRET=$(sed -n 's/^CABINET_CRON_SECRET=//p' "$DIR/.env" 2>/dev/null | head -n 1 | tr -d '\r' \
  | sed -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'$/\1/")

if [ -z "$SECRET" ]; then
  echo "$(date -Is) рассылка выключена: CABINET_CRON_SECRET не задан в deploy/.env"
  exit 0
fi

# Приложение слушает только петлю, прокси в этом вызове не участвует.
# Секрет должен состоять из знаков ASCII: заголовки HTTP переносят кириллицу
# в искажённом виде, и маршрут отвечал бы «не найдено» при верном на вид
# значении. `openssl rand -base64` даёт ровно такой набор знаков.
if ! ANSWER=$(curl -fsS --noproxy '*' -m 30 -X POST -H "x-cabinet-cron: $SECRET" "$URL"); then
  echo "$(date -Is) ОШИБКА: маршрут рассылки не ответил" >&2
  exit 1
fi

# Строка в журнал пишется, только когда что-то произошло: иначе расписание
# наполняло бы журнал полутора тысячами строк «ничего не делалось» в сутки,
# и настоящая ошибка терялась бы среди них.
# Сроки согласования (Р-290) — тоже событие: поставленный срок и этап,
# принятый по п. 7.3 оферты, в журнале видны всегда.
quiet=1
for key in reminders approvalReminders deadlinesStarted autoAccepted sent failed; do
  case "$ANSWER" in
    *"\"$key\":0"*) ;;
    *) quiet=0 ;;
  esac
done
[ "$quiet" -eq 1 ] && exit 0

echo "$(date -Is) рассылка: $ANSWER"
